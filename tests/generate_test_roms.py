from pathlib import Path
import sys

output = Path(sys.argv[1])

script_name = "[GENERATE_TEST_ROM]"

blank_memory = 512
memory_size = 4096
max_rom_size = memory_size - blank_memory

roms = {
    "Load.ch8":         [0x01] * max_rom_size,
    "OP_0x00E0.ch8":    [0x00, 0xE0],
    "OP_0x00EE.ch8":    [0x22, 0x04, 0x00, 0x00, 0x00, 0xEE],
    "OP_0X0NNN.ch8":    [0x03, 0x00],
    "OP_0x1NNN.ch8":    [0x03, 0x00],
    "OP_0x2NNN.ch8":    [0x22, 0x22],
    "OP_0x3XNN.ch8":    [0x60, 0x0A, 0x30, 0x05, 0x61, 0x14, 0x31, 0x14,
                         0x00, 0xE0, 0x6F, 0x0A, 0x3F, 0x0A, 0x00, 0xE0],
    "OP_0x6XNN.ch8":    [0x60, 0x00, 0x61, 0x01, 0x62, 0x02, 0x63, 0x03,
                         0x64, 0x04, 0x65, 0x05, 0x66, 0x06, 0x67, 0x07,
                         0x68, 0x08, 0x69, 0x09, 0x6A, 0x0A, 0x6B, 0x0B,
                         0x6C, 0x0C, 0x6D, 0x0D, 0x6E, 0x0E, 0x6F, 0x0F],
}

# output = Path("test_roms")
output.mkdir(parents=True, exist_ok=True)

for filename, program in roms.items():
    if len(program) > max_rom_size:
        print(script_name + " Rom is to large: " + 
              filename + "size: " + str(len(program)) + " bytes")
    (output / filename).write_bytes(bytes(program))